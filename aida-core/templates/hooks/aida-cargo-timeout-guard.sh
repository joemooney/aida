#!/bin/bash
# AIDA cargo time-budget hint — PreToolUse hook for Claude Code and Codex.
#
# Warns (never blocks) when a shell command wraps cargo or make in an outer
# GNU `timeout <N>`. That clock starts when the command is issued, so time
# spent waiting for a cargo build slot on a busy host counts against it, and
# the run is killed mid-build and usually retried, re-queueing behind itself.
# The suggested replacement hands the budget to the cargo wrapper, which
# (once aida-host STORY-100 ships) starts the clock when the slot is acquired,
# and runs long work in the tool's background mode, where no foreground tool
# cap applies. Until then the variable is a no-op.
#
# Non-cargo timeouts (`timeout 540 gh pr checks ...`) are left alone. Prose
# that only mentions the pattern (a quoted argument, heredoc body or comment)
# is not a command and is not flagged. A `timeout <N> bash -c "..."` (or sh,
# zsh, dash) is flagged when the quoted body runs cargo or make. A make target
# is passed over only when the Makefile in the command's directory shows that
# it and every prerequisite run only known-inert commands (echo, cp, ...);
# anything it cannot resolve still gets the hint, and so does a line where any
# other timeout-wrapped segment runs cargo. Known misses: cargo reached
# through `eval`, an alias or a function, and an interpreter on the inert list
# (`grep`, `cat`, `test`) given a file that is itself generated by cargo.
# Make conditionals, `.RECIPEPREFIX` (assigned or `define`d), `$(eval ...)`,
# a top-level line that expands a variable outside an assignment, pattern or
# suffix rules (over GNU make's default suffixes plus `.SUFFIXES:`) that could
# build an unknown prerequisite, and `<(...)` process substitution are all
# treated as unresolvable, so they get the hint.
#
# trace:STORY-1854 | ai:claude
# trace:TASK-1967 | ai:claude

set -Euo pipefail

# Warn-only: no failure inside this hook may block the tool call.
trap 'exit 0' ERR

INPUT=$(cat)

# Deliberately duplicated from aida-git-guardrails.sh: scaffolded hooks are
# self-contained, so keep this parser byte-identical in every hook template.
__aida_json_field() {
    local field="$1"
    awk -v wanted="$field" '
    { text = text (NR > 1 ? "\n" : "") $0 }
    END {
        pattern = "\"" wanted "\"[ \t\r\n]*:[ \t\r\n]*\""
        from = 1
        while (from <= length(text) && match(substr(text, from), pattern)) {
            start = from + RSTART - 1
            before = start - 1
            while (before > 0 && substr(text, before, 1) ~ /[ \t\r\n]/) before--
            # Valid JSON escapes quotes of nested keys, so this branch is unreachable
            # for well-formed input and is deliberately untested; retain malformed-input defense.
            if (before == 0 || (substr(text, before, 1) != "{" && substr(text, before, 1) != ",")) {
                from = start + RLENGTH
                continue
            }
            i = start + RLENGTH
            value = ""
            while (i <= length(text)) {
                c = substr(text, i, 1)
                if (c == "\"") { printf "%s", value; exit }
                if (c == "\\" && i < length(text)) {
                    e = substr(text, i + 1, 1)
                    if (e == "\"" || e == "\\" || e == "/") value = value e
                    else if (e == "n") value = value "\n"
                    else if (e == "r") value = value "\r"
                    else if (e == "t") value = value "\t"
                    else if (e == "u") value = value "\\u" # Leave \uXXXX escapes as-is.
                    else value = value "\\" e
                    i += 2
                } else { value = value c; i++ }
            }
            exit
        }
    }'
}

# Deliberately duplicated from aida-git-guardrails.sh (byte-identical): blank
# out quoted bodies, heredoc bodies and comments so prose is not scanned.
strip_shell_literals() {
    printf '%s' "$1" | awk '
    BEGIN { SQ = "\047"; DQ = "\042"; BS = "\\"; st = "N"; nq = 0; hi = 0; inhd = 0; ar = 0; bad = 0 }
    {
        line = $0
        if (inhd) {
            cmp = line
            if (hstrip[hi]) sub(/^\t+/, "", cmp)
            if (cmp == hdelim[hi]) {
                hi++
                if (hi > nq) { inhd = 0; nq = 0; hi = 0 }
            }
            next
        }
        out = ""; n = length(line); i = 1; cont = 0
        while (i <= n) {
            c = substr(line, i, 1)
            if (st == "S") {
                if (c == SQ) { st = "N"; out = out c }
                i++; continue
            }
            if (st == "A" || st == "D") {
                if (c == BS) { i += 2; continue }
                if ((st == "A" && c == SQ) || (st == "D" && c == DQ)) { st = "N"; out = out c }
                i++; continue
            }
            # Unquoted text.
            if (c == BS) {
                if (i == n) { cont = 1; out = out " "; i++; continue }
                out = out substr(line, i, 2); i += 2; continue
            }
            if (c == SQ) {
                st = (substr(out, length(out), 1) == "$") ? "A" : "S"
                out = out c; i++; continue
            }
            if (c == DQ) { st = "D"; out = out c; i++; continue }
            if (c == "#" && (i == 1 || substr(line, i - 1, 1) ~ /[ \t;&|(]/)) break
            if (substr(line, i, 2) == "((") { ar++; out = out "(("; i += 2; continue }
            if (ar > 0 && substr(line, i, 2) == "))") { ar--; out = out "))"; i += 2; continue }
            if (substr(line, i, 3) == "<<<") { out = out "<<<"; i += 3; continue }
            if (ar == 0 && substr(line, i, 2) == "<<") {
                j = i + 2; strip = 0
                if (substr(line, j, 1) == "-") { strip = 1; j++ }
                while (j <= n && substr(line, j, 1) ~ /[ \t]/) j++
                d = ""
                while (j <= n) {
                    ch = substr(line, j, 1)
                    if (ch ~ /[ \t;&|<>()]/) break
                    if (ch != SQ && ch != DQ && ch != BS) d = d ch
                    j++
                }
                if (d == "") bad = 1
                else { nq++; hdelim[nq] = d; hstrip[nq] = strip }
                out = out substr(line, i, j - i); i = j; continue
            }
            out = out c; i++
        }
        if (st == "N" && !cont) {
            printf "%s\n", out
            if (nq > 0) { inhd = 1; hi = 1 }
        } else {
            printf "%s", out
        }
    }
    END { if (st != "N" || inhd || bad) exit 3 }'
}

COMMAND=$(printf '%s' "$INPUT" | __aida_json_field command)
[ -n "$COMMAND" ] || exit 0
# Cheap pre-filter: the common call never names timeout at all.
case "$COMMAND" in
    *timeout*) ;;
    *) exit 0 ;;
esac

# An unparseable command (unterminated quote or heredoc) is scanned raw: a
# spurious hint is harmless, a missed one is the failure this hook prevents.
SCAN=$(strip_shell_literals "$COMMAND") || SCAN=$COMMAND

# `timeout [options] <duration> [env] [VAR=value ...] cargo|make ...`, at a
# command position, with the duration captured. trace:STORY-1854 | ai:claude
WORD='[^[:space:];&|()]'
OPT="(-[ks][[:space:]]*${WORD}+|--(kill-after|signal)(=|[[:space:]]+)${WORD}+|--foreground|--preserve-status|-v|--verbose)"
ASSIGN="(env|[A-Za-z_][A-Za-z0-9_]*=${WORD}*)"
TIMEOUT_PREFIX="(^|[[:space:];&|(\`])(${WORD}*/)?g?timeout[[:space:]]+(${OPT}[[:space:]]+)*([0-9]+(\.[0-9]+)?[smhd]?)[[:space:]]+(${ASSIGN}[[:space:]]+)*"
TOOL_TAIL="(${WORD}*/)?(cargo|g?make)([[:space:];&|)]|$)"
PATTERN="${TIMEOUT_PREFIX}${TOOL_TAIL}"
# `timeout <N> bash -c "<body>"`: the body is a quoted literal, so the
# stripped scan sees only its quote; it is read from the raw command.
# trace:TASK-1967 | ai:claude
SHELL_C="(${WORD}*/)?(ba|da|z|k)?sh[[:space:]]+((-[A-Za-z]+|[-+]o[[:space:]]+${WORD}+)[[:space:]]+)*-[A-Za-z]*c[[:space:]]*"
DQ_BODY='"(([^"\\]|\\.)*)"'
SQ_BODY="'([^']*)'"
SHELL_RAW="${TIMEOUT_PREFIX}${SHELL_C}(${DQ_BODY}|${SQ_BODY})"
# Inside a body: cargo or make at a command position, after optional env
# assignments, wrappers such as `nice -n 10`, and shell keywords.
WRAPPER="((exec|time|command|nohup|nice|if|then|else|elif|while|until|do|\{|!)[[:space:]]+(-n[[:space:]]*-?[0-9]+[[:space:]]+)?)"
BODY_PATTERN="(^|[;&|(\`])[[:space:]]*${WRAPPER}*(${ASSIGN}[[:space:]]+)*${TOOL_TAIL}"
CD_PATTERN='(^|[;&|(`])[[:space:]]*(cd|pushd)([[:space:]]|$)'

# The directory the command runs in: the payload's cwd, else this process's.
RUN_DIR=$(printf '%s' "$INPUT" | __aida_json_field cwd)
[ -n "$RUN_DIR" ] && [ -d "$RUN_DIR" ] || RUN_DIR=$PWD

# True (0) only when every named make target, resolved through the Makefile
# in RUN_DIR, runs only known-inert commands (echo, printf, ls, cp ...), and
# so cannot reach cargo. Anything else is not shown safe: an unknown target,
# a make variable or command substitution, an include anywhere in the
# Makefile, or a prerequisite list naming a variable. trace:TASK-1967 | ai:claude
make_targets_skip_cargo() {
    local makefile=""
    local f
    for f in GNUmakefile makefile Makefile; do
        if [ -f "$RUN_DIR/$f" ]; then makefile=$RUN_DIR/$f; break; fi
    done
    [ -n "$makefile" ] && [ "$#" -gt 0 ] || return 1
    awk -v wanted="$*" '
    function inert(cmd,   c, parts, n, k, w) {
        c = cmd
        gsub(/\$\$\{[A-Za-z_][A-Za-z0-9_]*\}/, "", c)
        gsub(/\$\$[A-Za-z_][A-Za-z0-9_]*/, "", c)
        gsub(/\$[@<^*?]/, "", c)
        if (c ~ /[$`]/) return 0
        # Process substitution runs a command. trace:TASK-1955 | ai:claude (TASK-2077)
        if (c ~ /[<>]\(/) return 0
        gsub(/\047[^\047]*\047/, "\047\047", c)
        gsub(/"[^"]*"/, "\"\"", c)
        n = split(c, parts, /;|&&|\|\||\||&/)
        for (k = 1; k <= n; k++) {
            w = parts[k]
            sub(/^[ \t@+-]*/, "", w)
            sub(/[ \t<>].*$/, "", w)
            if (w == "") continue
            # awk and sed can execute commands from their quoted programs,
            # which are stripped above, so neither is inert.
            # trace:TASK-1955 | ai:claude (TASK-2077)
            if (w !~ /^(echo|printf|true|false|:|ls|cat|grep|mkdir|rm|cp|mv|touch|test|\[)$/) return 0
        }
        return 1
    }
    BEGIN {
        owner = ""; incont = 0; indef = 0
        # GNU make'"'"'s default suffix list; `.SUFFIXES:` adds to it, or clears it
        # with no prerequisites. A `.X` / `.X.Y` target is a suffix rule only
        # when its suffixes are known, so `.venv:` or `.env:` is a plain target
        # and an upper-case `.C:` is no special target.
        # trace:TASK-1955 | ai:claude (TASK-2128, TASK-2129)
        n = split(".out .a .ln .o .c .cc .C .cpp .p .f .F .m .r .y .l .ym .yl .s .S .mod .sym .def .h .info .dvi .tex .texinfo .texi .txinfo .w .ch .web .sh .elc .el", sfx, " ")
        for (k = 1; k <= n; k++) suffix[sfx[k]] = 1
    }
    indef { if ($0 ~ /^[ \t]*endef/) indef = 0; next }
    /^\t/ || incont {
        # A recipe line, or the continuation of one, whatever its indent.
        incont = ($0 ~ /\\$/)
        line = $0
        sub(/\\$/, "", line)
        if (owner != "") {
            n = split(owner, os, " ")
            for (k = 1; k <= n; k++) if (!inert(line)) bad[os[k]] = 1
        }
        next
    }
    /^[ \t]*(#|$)/ { next }
    # A multi-line .RECIPEPREFIX definition changes what a recipe is too.
    # trace:TASK-1955 | ai:claude (TASK-2128)
    /^[ \t]*((override|export|private)[ \t]+)*define[ \t]+\.RECIPEPREFIX([ \t:+?!=]|$)/ { unresolvable = 1; exit }
    /^[ \t]*((override|export|private)[ \t]+)*define[ \t]/ { indef = 1; owner = ""; next }
    # An include can add prerequisites or recipes to any target.
    /^[ \t]*-?s?include[ \t]/ { unresolvable = 1; exit }
    # A conditional can hide recipe lines from their target; .RECIPEPREFIX
    # and $(eval ...) change what a recipe or rule is. None is resolved here.
    # trace:TASK-1955 | ai:claude (TASK-2075, TASK-2077)
    /^[ \t]*(ifeq|ifneq|ifdef|ifndef)([ \t(]|$)/ { unresolvable = 1; exit }
    /^[ \t]*((override|export|private)[ \t]+)*\.RECIPEPREFIX[ \t:+?!]*=/ { unresolvable = 1; exit }
    /\$[({]eval[ \t]/ { unresolvable = 1; exit }
    {
        line = $0
        while (line ~ /\\$/ && (getline nxt) > 0) line = substr(line, 1, length(line) - 1) " " nxt
        sub(/[ \t]#.*$/, "", line)
        c = index(line, ":")
        head = substr(line, 1, c - 1)
        # Outside an assignment, an expansion before the rule colon (or a
        # bare `$(X)` line) can expand to a whole rule or a computed target.
        # trace:TASK-1955 | ai:claude (TASK-2128)
        eq = index(line, "=")
        if (eq == 0 || (c > 0 && c < eq)) {
            lead = (c > 0) ? head : line
            if (lead ~ /\$/) { unresolvable = 1; exit }
        }
        if (c == 0 || head ~ /[=$]/ || substr(line, c + 1, 1) == "=") { owner = ""; next }
        body = substr(line, c + 1)
        sub(/^:/, "", body)
        if (body ~ /=/) { owner = ""; next }
        inline = ""
        s = index(body, ";")
        if (s > 0) { inline = substr(body, s + 1); body = substr(body, 1, s - 1) }
        gsub(/\|/, " ", body)
        owner = ""
        n = split(head, ts, /[ \t]+/)
        for (k = 1; k <= n; k++) {
            if (ts[k] == "") continue
            known[ts[k]] = 1
            deps[ts[k]] = deps[ts[k]] " " body
            # A pattern rule or a variable prerequisite cannot be resolved here.
            if (head ~ /%/ || body ~ /[$%]/) bad[ts[k]] = 1
            # A pattern or old-style suffix rule (`.md.html:`, `.c:`) may build
            # any prerequisite this Makefile names nowhere else.
            # trace:TASK-1955 | ai:claude (TASK-2076)
            if (ts[k] ~ /%/) implicit = 1
            else if (ts[k] ~ /^\.[^.\/]+(\.[^.\/]+)?$/) maybe_suffix[ts[k]] = 1
            if (ts[k] == ".SUFFIXES") {
                if (body ~ /^[ \t]*$/) { delete suffix; delete declared }
                m = split(body, sl, /[ \t]+/)
                for (j = 1; j <= m; j++) if (sl[j] != "") suffix[sl[j]] = 1
            }
            if (inline != "" && !inert(inline)) bad[ts[k]] = 1
            owner = owner " " ts[k]
        }
    }
    END {
        # `exit` in a rule still runs END: an unresolvable Makefile must not
        # fall through to the resolution below. trace:TASK-1955 | ai:claude (TASK-2075)
        if (unresolvable) exit 1
        for (t in maybe_suffix) {
            r = substr(t, 2)
            d = index(r, ".")
            if (d == 0 ? ("." r) in suffix : (("." substr(r, 1, d - 1)) in suffix && ("." substr(r, d + 1)) in suffix)) implicit = 1
        }
        n = split(wanted, queue, " ")
        for (i = 1; i <= n; i++) {
            t = queue[i]
            if (t == "" || seen[t]++) continue
            if (!(t in known)) {
                # A plain file prerequisite is fine, unless an implicit rule
                # here could build it; a top-level target never is.
                if (i <= top || implicit) exit 1
                continue
            }
            if (t in bad) exit 1
            m = split(deps[t], ds, /[ \t]+/)
            for (k = 1; k <= m; k++) if (ds[k] != "") queue[++n] = ds[k]
        }
        exit 0
    }' top="$#" "$makefile"
}

# The make targets named after the matched `make` word, up to the end of that
# simple command. Prints nothing, and fails, when the arguments cannot be
# resolved here (a -C/-f directory or file switch, a quoted target).
make_targets_from() {
    local args=${1%%[;&|)]*}
    local -a words targets=()
    local w
    read -r -a words <<< "$args"
    for w in "${words[@]}"; do
        case "$w" in
            -C*|-f*|-I*|-o*|-W*|--directory*|--file*|--makefile*|--include-dir*|--old-file*|--what-if*|--new-file*|--assume*) return 1 ;;
            *[\"\'\\\$\`]*) return 1 ;;
            -*|*=*) ;;
            *) [[ "$w" =~ ^[0-9.]+$ ]] || targets+=("$w") ;;
        esac
    done
    [ "${#targets[@]}" -gt 0 ] || return 1
    printf '%s\n' "${targets[*]}"
}

# Every timeout-wrapped cargo/make on the line is a segment. The hint is
# skipped only when every segment is a make target shown not to reach cargo;
# the first other segment names the hint. A `cd` anywhere means RUN_DIR's
# Makefile may not be the one that runs. trace:TASK-1967 | ai:claude
duration=""
tool=""
shown=""
moved=0
[[ "$SCAN" =~ $CD_PATTERN ]] && moved=1

# Record one segment: $1 duration, $2 tool, $3 the text after the tool word
# (empty when the arguments end at a separator), $4 how the hint shows it.
consider() {
    [ -z "$duration" ] || return 0
    if [ "$2" != cargo ] && [ "$moved" = 0 ]; then
        local targets
        if targets=$(make_targets_from "$3") && make_targets_skip_cargo $targets; then
            return 0
        fi
    fi
    duration=$1
    tool=$2
    shown=$4
}

# What follows the matched text, or nothing when the match ended on a
# separator (so the command's arguments are already over).
after_match() {
    local text=$1 match=$2
    [[ "$match" =~ [[:space:]]$ ]] || return 0
    printf '%s' "${text#*"$match"}"
}

while IFS= read -r line; do
    rem=$line
    while [[ "$rem" =~ $PATTERN ]]; do
        m=${BASH_REMATCH[0]}
        consider "${BASH_REMATCH[7]}" "${BASH_REMATCH[12]}" "$(after_match "$rem" "$m")" \
            "timeout ${BASH_REMATCH[7]} ${BASH_REMATCH[12]}"
        rem=${rem#*"$m"}
    done
done <<< "$SCAN"

# Each `timeout <N> sh -c` with its own body. An occurrence inside a quoted
# argument, heredoc or comment is prose: appending a marker to the raw text
# before it and stripping must leave the marker intact.
rem=$COMMAND
seen_text=""
while [[ "$rem" =~ $SHELL_RAW ]]; do
    m=${BASH_REMATCH[0]}
    sh_duration=${BASH_REMATCH[7]}
    before=${rem%%"$m"*}
    seen_text+=$before
    rem=${rem#*"$m"}
    probe=$(strip_shell_literals "${seen_text}__AIDA_AT__") || probe=""
    seen_text+=$m
    [[ "$probe" == *__AIDA_AT__ ]] || continue
    body=""
    if [[ "$m" =~ ${DQ_BODY}$ ]] || [[ "$m" =~ ${SQ_BODY}$ ]]; then
        body=${BASH_REMATCH[1]}
    fi
    body_scan=$(strip_shell_literals "$body") || body_scan=$body
    [[ "$body_scan" =~ $CD_PATTERN ]] && body_moved=1 || body_moved=0
    while IFS= read -r body_line; do
        brem=$body_line
        while [[ "$brem" =~ $BODY_PATTERN ]]; do
            bm=${BASH_REMATCH[0]}
            btool=${BASH_REMATCH[8]}
            bafter=$(after_match "$brem" "$bm")
            [ "$body_moved" = 1 ] && bafter=""
            consider "$sh_duration" "$btool" "$bafter" "timeout ${sh_duration} sh -c \"${btool} ...\""
            brem=${brem#*"$bm"}
        done
    done <<< "$body_scan"
done
[ -n "$duration" ] || exit 0

case "$tool" in
    cargo) replacement="AIDA_CARGO_TIMEOUT=${duration} cargo ..." ;;
    *) replacement="AIDA_CARGO_TIMEOUT=${duration} ${tool} <target>" ;;
esac

MESSAGE="Cargo time budget: \`${shown}\` starts its clock before the cargo slot queue, so a long wait for a build slot can kill the run partway through. Write \`${replacement}\` instead, and run anything that can take more than about 10 minutes in the tool's background mode. Once the host cargo wrapper supports AIDA_CARGO_TIMEOUT (aida-host STORY-100), it starts that budget when the slot is acquired; until then it ignores the variable, and background mode is the only protection. After a timeout or KILLED, check \`cargo ps\` before retrying; never retry blindly."

# JSON-escape the message (it holds backticks and quotes, no newlines).
escaped=${MESSAGE//\\/\\\\}
escaped=${escaped//\"/\\\"}
printf '{"hookSpecificOutput":{"hookEventName":"PreToolUse","additionalContext":"%s"}}\n' "$escaped"
exit 0
